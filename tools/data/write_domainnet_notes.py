"""Write data/README.md from the DomainNet train/test lists in $DATA.

The numbers in that file come only from this script, so they can be regenerated:

    DATA=/path/to/datasets PYTHONPATH="${PWD}" python tools/data/write_domainnet_notes.py
"""
import logging
import os
from collections import Counter
from pathlib import Path

from utils.domainnet import (
    LAST_BASE_LABEL,
    NUM_CLASSES,
    STYLES,
    group_of,
    label_to_folder,
    read_all_lists,
)
from utils.methods import NUM_SHOTS

OUTPUT_PATH = Path(__file__).resolve().parents[2] / "data" / "README.md"

INTRO = """# Data notes

Generated by `tools/data/write_domainnet_notes.py`. Do not edit by hand.

## DomainNet lists

The project uses the lists that the [official page](http://ai.bu.edu/M3SDA/) marks "cleaned version,
recommended", from `multi-source/domainnet/txt/`. The downloaded zips also hold the images these
lists removed, so only images named in the lists are used.

All styles share one fixed split of the {num_classes} classes: labels 0-{last_base} are base and
{first_new}-{last_label} are new. The split does not depend on which classes a style's lists contain.
"""


def label_counts(entries):
    counts = Counter(label for _, _, label in entries)
    return [counts[label] for label in range(NUM_CLASSES)]


def image_count_table(all_entries):
    lines = ["| Style | Train images | Test images |", "| --- | --- | --- |"]
    for style in STYLES:
        lines.append(
            f"| {style} | {len(all_entries[(style, 'train')])} "
            f"| {len(all_entries[(style, 'test')])} |"
        )
    return "\n".join(lines)


def gap_table(all_entries, names):
    lines = ["| Style | Split | Label | Class | Group |", "| --- | --- | --- | --- | --- |"]
    for (style, split), entries in all_entries.items():
        for label, count in enumerate(label_counts(entries)):
            if count == 0:
                lines.append(f"| {style} | {split} | {label} | {names[label]} | {group_of(label)} |")
    return "\n".join(lines)


def format_short_classes(labels, counts, names):
    if not labels:
        return "none"
    return ", ".join(f"{names[label]} ({counts[label]})" for label in labels)


def short_class_table(all_entries, names):
    lines = [
        "| Style | Classes | Base classes, images | New classes, images |",
        "| --- | --- | --- | --- |",
    ]
    for style in STYLES:
        counts = label_counts(all_entries[(style, "train")])
        short = [label for label, count in enumerate(counts) if count < NUM_SHOTS]
        base = [label for label in short if group_of(label) == "base"]
        new = [label for label in short if group_of(label) == "new"]
        lines.append(
            f"| {style} | {len(short)} | {format_short_classes(base, counts, names)} "
            f"| {format_short_classes(new, counts, names)} |"
        )
    return "\n".join(lines)


def build_notes(all_entries, names):
    intro = INTRO.format(
        num_classes=NUM_CLASSES,
        last_base=LAST_BASE_LABEL,
        first_new=LAST_BASE_LABEL + 1,
        last_label=NUM_CLASSES - 1,
    )
    sections = [
        intro,
        "### Images per style\n",
        image_count_table(all_entries),
        "\n### Classes with no images in a list\n",
        gap_table(all_entries, names),
        f"\n### Classes with fewer than {NUM_SHOTS} training images\n",
        f"A {NUM_SHOTS}-shot draw keeps every image of these classes. "
        "The number in brackets is the class's training images.\n",
        short_class_table(all_entries, names),
    ]
    return "\n".join(sections) + "\n"


def main():
    logging.basicConfig(level=logging.INFO, format="%(levelname)s: %(message)s")
    data_root = os.environ.get("DATA")
    if not data_root:
        raise RuntimeError("Expected DATA to name the datasets folder, found it unset or empty.")

    all_entries = read_all_lists(Path(data_root) / "domainnet" / "splits")
    names = label_to_folder(all_entries)
    OUTPUT_PATH.parent.mkdir(exist_ok=True)
    OUTPUT_PATH.write_text(build_notes(all_entries, names))
    logging.info("Wrote %s", OUTPUT_PATH)


if __name__ == "__main__":
    main()
